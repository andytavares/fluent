# Run: python3 exemplar.py

from collections import deque

NUCLEOTIDES = ["A", "C", "G", "T"]


def min_mutation(start_gene, end_gene, bank):
    """BFS over the implicit gene graph: states are bank genes, edges are
    single-nucleotide changes. Candidates are generated by substitution
    (8 positions x 3 other letters) and filtered through the bank set --
    never by comparing all bank pairs. Removing a gene from the set at
    enqueue time is the visited mark. The answer counts edges (mutations).
    O(B) time with constant factor 8 x 4, O(B) space.
    """
    if start_gene == end_gene:
        return 0
    valid = set(bank)
    if end_gene not in valid:
        return -1
    queue = deque([(start_gene, 0)])
    valid.discard(start_gene)  # never revisit the start
    while queue:
        gene, mutations = queue.popleft()
        for i in range(len(gene)):
            for ch in NUCLEOTIDES:
                if ch == gene[i]:
                    continue
                nxt = gene[:i] + ch + gene[i + 1:]
                if nxt not in valid:
                    continue
                if nxt == end_gene:
                    return mutations + 1
                valid.discard(nxt)  # visited-on-push
                queue.append((nxt, mutations + 1))
    return -1


def ladder_length(begin_word, end_word, word_list):
    """Identical BFS over the word graph, with two differences: the
    alphabet is a-z, and the answer counts WORDS in the chain (edges + 1),
    so the start distance is 1. The word set doubles as the visited set --
    a word is removed the moment it is enqueued, which BFS makes safe: the
    first route to any word is already a shortest one.
    O(N * L^2 * 26) time, O(N * L) space.
    """
    words = set(word_list)
    if end_word not in words:
        return 0
    queue = deque([(begin_word, 1)])
    words.discard(begin_word)
    while queue:
        word, length = queue.popleft()
        for i in range(len(word)):
            for code in range(ord("a"), ord("z") + 1):
                ch = chr(code)
                if ch == word[i]:
                    continue
                nxt = word[:i] + ch + word[i + 1:]
                if nxt not in words:
                    continue
                if nxt == end_word:
                    return length + 1
                words.discard(nxt)  # visited-on-push
                queue.append((nxt, length + 1))
    return 0


def main():
    print(min_mutation("AACCGGTT", "AACCGGTA", ["AACCGGTA"]))  # 1
    print(min_mutation("AACCGGTT", "AAACGGTA", ["AACCGGTA", "AACCGCTA", "AAACGGTA"]))  # 2
    print(ladder_length("hit", "cog", ["hot", "dot", "dog", "lot", "log", "cog"]))  # 5
    print(ladder_length("hit", "cog", ["hot", "dot", "dog", "lot", "log"]))  # 0


if __name__ == "__main__":
    main()
