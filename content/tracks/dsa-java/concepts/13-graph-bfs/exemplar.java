import java.util.ArrayDeque;
import java.util.HashSet;
import java.util.List;
import java.util.Set;

class Solution {

    private static final char[] NUCLEOTIDES = { 'A', 'C', 'G', 'T' };

    // Pairs a BFS state (gene or word) with the step count used to reach it.
    private static class State {
        final String value;
        final int steps;
        State(String value, int steps) {
            this.value = value;
            this.steps = steps;
        }
    }

    // BFS over the implicit gene graph: states are bank genes, edges are
    // single-nucleotide changes. Candidates are generated by substitution
    // (8 positions x 3 other letters) and filtered through the bank set —
    // never by comparing all bank pairs. Removing a gene from the set at
    // enqueue time is the visited mark. The answer counts edges (mutations).
    // O(B) time with constant factor 8 x 4, O(B) space.
    public static int minMutation(String startGene, String endGene, String[] bank) {
        if (startGene.equals(endGene)) return 0;
        Set<String> valid = new HashSet<>(List.of(bank));
        if (!valid.contains(endGene)) return -1;

        var queue = new ArrayDeque<State>();
        queue.offer(new State(startGene, 0));
        valid.remove(startGene); // never revisit the start

        while (!queue.isEmpty()) {
            State cur = queue.poll();
            char[] chars = cur.value.toCharArray();
            for (int i = 0; i < chars.length; i++) {
                char original = chars[i];
                for (char ch : NUCLEOTIDES) {
                    if (ch == original) continue;
                    chars[i] = ch;
                    String next = new String(chars);
                    if (!valid.contains(next)) continue;
                    if (next.equals(endGene)) return cur.steps + 1;
                    valid.remove(next); // visited-on-push
                    queue.offer(new State(next, cur.steps + 1));
                }
                chars[i] = original;
            }
        }
        return -1;
    }

    // Identical BFS over the word graph, with two differences: the alphabet
    // is a-z, and the answer counts WORDS in the chain (edges + 1), so the
    // start distance is 1. The word set doubles as the visited set — a word
    // is removed the moment it is enqueued, which BFS makes safe: the first
    // route to any word is already a shortest one.
    // O(N * L^2 * 26) time, O(N * L) space.
    public static int ladderLength(String beginWord, String endWord, List<String> wordList) {
        Set<String> words = new HashSet<>(wordList);
        if (!words.contains(endWord)) return 0;

        var queue = new ArrayDeque<State>();
        queue.offer(new State(beginWord, 1));
        words.remove(beginWord);

        while (!queue.isEmpty()) {
            State cur = queue.poll();
            char[] chars = cur.value.toCharArray();
            for (int i = 0; i < chars.length; i++) {
                char original = chars[i];
                for (char ch = 'a'; ch <= 'z'; ch++) {
                    if (ch == original) continue;
                    chars[i] = ch;
                    String next = new String(chars);
                    if (!words.contains(next)) continue;
                    if (next.equals(endWord)) return cur.steps + 1;
                    words.remove(next); // visited-on-push
                    queue.offer(new State(next, cur.steps + 1));
                }
                chars[i] = original;
            }
        }
        return 0;
    }

    public static void main(String[] args) {
        System.out.println(minMutation("AACCGGTT", "AACCGGTA", new String[]{"AACCGGTA"})); // 1
        System.out.println(minMutation("AACCGGTT", "AAACGGTA",
            new String[]{"AACCGGTA", "AACCGCTA", "AAACGGTA"})); // 2
        System.out.println(ladderLength("hit", "cog", List.of("hot", "dot", "dog", "lot", "log", "cog"))); // 5
        System.out.println(ladderLength("hit", "cog", List.of("hot", "dot", "dog", "lot", "log"))); // 0
    }
}
